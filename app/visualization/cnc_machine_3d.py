import plotly.graph_objects as go


class CNCMachine3D:

    def __init__(self):

        self.traces = []

    def add_box(
        self,
        fig,
        x0,
        x1,
        y0,
        y1,
        z0,
        z1,
        name,
        opacity=1.0,
    ):

        vertices = [
            (x0, y0, z0),
            (x1, y0, z0),
            (x1, y1, z0),
            (x0, y1, z0),
            (x0, y0, z1),
            (x1, y0, z1),
            (x1, y1, z1),
            (x0, y1, z1),
        ]

        x = [v[0] for v in vertices]
        y = [v[1] for v in vertices]
        z = [v[2] for v in vertices]

        i = [
            0, 0, 0,
            1, 1, 1,
            2, 2, 2,
            3, 3, 3,
        ]

        j = [
            1, 4, 3,
            2, 5, 0,
            3, 6, 1,
            0, 7, 2,
        ]

        k = [
            4, 5, 7,
            6, 6, 5,
            7, 7, 6,
            4, 4, 6,
        ]

        mesh = go.Mesh3d(
            x=x,
            y=y,
            z=z,
            i=i,
            j=j,
            k=k,
            opacity=opacity,
            name=name,
            hoverinfo="name",
        )

        fig.add_trace(mesh)

    def build(self):

        fig = go.Figure()

        # -------------------------------------------------
        # BASE
        # -------------------------------------------------

        self.add_box(
            fig,
            0, 100,
            0, 70,
            0, 5,
            "Base",
        )

        # -------------------------------------------------
        # MESA
        # -------------------------------------------------

        self.add_box(
            fig,
            5, 95,
            5, 65,
            5, 8,
            "Mesa",
        )

        # -------------------------------------------------
        # COLUMNAS LATERALES
        # -------------------------------------------------

        self.add_box(
            fig,
            5, 12,
            5, 65,
            8, 65,
            "Columna izquierda",
        )

        self.add_box(
            fig,
            88, 95,
            5, 65,
            8, 65,
            "Columna derecha",
        )

        # -------------------------------------------------
        # GANTRY
        # -------------------------------------------------

        self.add_box(
            fig,
            5, 95,
            55, 65,
            55, 68,
            "Gantry",
        )

        # -------------------------------------------------
        # GUIAS DEL GANTRY
        # -------------------------------------------------

        self.add_box(
            fig,
            12, 88,
            58, 61,
            45, 48,
            "Guia X",
        )

        # -------------------------------------------------
        # CARRO X
        # -------------------------------------------------

        self.add_box(
            fig,
            43, 57,
            55, 65,
            40, 58,
            "Carro X",
        )

        # -------------------------------------------------
        # EJE Z
        # -------------------------------------------------

        self.add_box(
            fig,
            46, 54,
            58, 62,
            25, 58,
            "Eje Z",
        )

        # -------------------------------------------------
        # SPINDLE
        # -------------------------------------------------

        self.add_box(
            fig,
            44, 56,
            57, 63,
            18, 32,
            "Spindle",
        )

        # -------------------------------------------------
        # HERRAMIENTA
        # -------------------------------------------------

        self.add_box(
            fig,
            48, 52,
            59, 61,
            8, 20,
            "Herramienta",
        )

        # -------------------------------------------------
        # PIEZA
        # -------------------------------------------------

        self.add_box(
            fig,
            25, 75,
            20, 50,
            8, 18,
            "Material",
            opacity=0.65,
        )

        # -------------------------------------------------
        # RANURAS DE LA MESA
        # -------------------------------------------------

        for y in [15, 25, 35, 45, 55]:

            fig.add_trace(
                go.Scatter3d(
                    x=[10, 90],
                    y=[y, y],
                    z=[8.2, 8.2],
                    mode="lines",
                    line=dict(width=3),
                    showlegend=False,
                    hoverinfo="skip",
                )
            )

        return fig
